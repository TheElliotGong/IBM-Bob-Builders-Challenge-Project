/**
 * Client-side export helpers.
 * All functions run entirely in the browser — no server round-trip.
 */

import type { ParsedMission, RankedVehicle, MatchedVehicle, ExplainResponse } from "./types";

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

function fmtUsd(v: number | null): string {
  if (v === null) return "—";
  if (v >= 1_000_000) return `$${(v / 1_000_000).toFixed(1)}M`;
  return `$${v.toLocaleString()}`;
}

function fmtNull(v: string | number | null | undefined): string {
  return v == null ? "—" : String(v);
}

export interface ExportPayload {
  mission: ParsedMission;
  ranked: RankedVehicle[];
  eliminated: MatchedVehicle[];
  explanation: ExplainResponse | null;
  generatedAt?: string;
}

function buildTextLines(payload: ExportPayload): string[] {
  const { mission, ranked, eliminated, explanation, generatedAt } = payload;
  const ts = generatedAt ?? new Date().toISOString();
  const lines: string[] = [];

  lines.push("=".repeat(60));
  lines.push("AI Launch Vehicle Selector — Mission Report");
  lines.push(`Generated: ${ts}`);
  lines.push("=".repeat(60));
  lines.push("");

  // Mission requirements
  lines.push("MISSION REQUIREMENTS");
  lines.push("-".repeat(40));
  lines.push(`Payload Mass:           ${fmtNull(mission.payload_mass_kg != null ? `${mission.payload_mass_kg} kg` : null)}`);
  lines.push(`Orbit Type:             ${fmtNull(mission.orbit_type)}`);
  lines.push(`Target Altitude:        ${fmtNull(mission.target_altitude_km != null ? `${mission.target_altitude_km} km` : null)}`);
  lines.push(`Budget Ceiling:         ${fmtUsd(mission.budget_usd)}`);
  lines.push(`Max Lead Time:          ${fmtNull(mission.schedule_months != null ? `${mission.schedule_months} months` : null)}`);
  lines.push(`Inclination Flex:       ${fmtNull(mission.inclination_flexibility_required)}`);
  lines.push(`Parse Confidence:       ${mission.parse_confidence.toUpperCase()}`);
  lines.push("");

  // AI explanation
  if (explanation) {
    lines.push("AI RECOMMENDATION");
    lines.push("-".repeat(40));
    lines.push(explanation.explanation);
    lines.push("");
  }

  // Ranked vehicles
  lines.push(`RANKED LAUNCH OPTIONS (${ranked.length} viable)`);
  lines.push("-".repeat(40));
  if (ranked.length === 0) {
    lines.push("No vehicles passed all constraints.");
  } else {
    ranked.forEach((m) => {
      lines.push(`#${m.rank}  ${m.entry.vehicle} (${m.entry.provider})`);
      lines.push(`    Type:          ${m.entry.type}`);
      lines.push(`    Score:         ${m.score}/100`);
      lines.push(`    Est. Cost:     ${fmtUsd(m.estimated_cost_usd)}`);
      lines.push(`    Lead Time:     ${m.entry.integration.lead_time_months.min}–${m.entry.integration.lead_time_months.max} months`);
      lines.push(`    Orbit Flex:    ${m.entry.orbit_options.inclination_flexibility}`);
      lines.push(`    Score Detail:  Cost ${m.score_breakdown.cost_score} | Schedule ${m.score_breakdown.schedule_score} | Orbit ${m.score_breakdown.orbit_score}`);
      lines.push("");
    });
  }

  // Eliminated vehicles
  if (eliminated.length > 0) {
    lines.push(`ELIMINATED OPTIONS (${eliminated.length})`);
    lines.push("-".repeat(40));
    eliminated.forEach((m) => {
      lines.push(`  ${m.entry.vehicle} (${m.entry.provider})`);
      if (m.elimination_reason) lines.push(`    Reason: ${m.elimination_reason}`);
    });
    lines.push("");
  }

  lines.push("=".repeat(60));
  lines.push("Generated by IBM Bob Builders Challenge — AI Launch Vehicle Selector");
  return lines;
}

function buildMarkdown(payload: ExportPayload): string {
  const { mission, ranked, eliminated, explanation, generatedAt } = payload;
  const ts = generatedAt ?? new Date().toISOString();
  const md: string[] = [];

  md.push("# AI Launch Vehicle Selector — Mission Report");
  md.push(`*Generated: ${ts}*`);
  md.push("");

  md.push("## Mission Requirements");
  md.push("");
  md.push("| Field | Value |");
  md.push("|---|---|");
  md.push(`| Payload Mass | ${fmtNull(mission.payload_mass_kg != null ? `${mission.payload_mass_kg} kg` : null)} |`);
  md.push(`| Orbit Type | ${fmtNull(mission.orbit_type)} |`);
  md.push(`| Target Altitude | ${fmtNull(mission.target_altitude_km != null ? `${mission.target_altitude_km} km` : null)} |`);
  md.push(`| Budget Ceiling | ${fmtUsd(mission.budget_usd)} |`);
  md.push(`| Max Lead Time | ${fmtNull(mission.schedule_months != null ? `${mission.schedule_months} months` : null)} |`);
  md.push(`| Inclination Flexibility | ${fmtNull(mission.inclination_flexibility_required)} |`);
  md.push(`| Parse Confidence | **${mission.parse_confidence.toUpperCase()}** |`);
  md.push("");

  if (explanation) {
    md.push("## AI Recommendation");
    md.push("");
    md.push(explanation.explanation);
    md.push("");
  }

  md.push(`## Ranked Launch Options (${ranked.length} viable)`);
  md.push("");
  if (ranked.length === 0) {
    md.push("> No vehicles passed all constraints.");
  } else {
    md.push("| Rank | Vehicle | Provider | Score | Est. Cost | Lead Time | Orbit Flex |");
    md.push("|---|---|---|---|---|---|---|");
    ranked.forEach((m) => {
      md.push(
        `| #${m.rank} | ${m.entry.vehicle} | ${m.entry.provider} | ${m.score} | ${fmtUsd(m.estimated_cost_usd)} | ${m.entry.integration.lead_time_months.min}–${m.entry.integration.lead_time_months.max} mo | ${m.entry.orbit_options.inclination_flexibility} |`
      );
    });
  }
  md.push("");

  if (eliminated.length > 0) {
    md.push(`## Eliminated Options (${eliminated.length})`);
    md.push("");
    eliminated.forEach((m) => {
      md.push(`- **${m.entry.vehicle}** (${m.entry.provider})${m.elimination_reason ? ` — ${m.elimination_reason}` : ""}`);
    });
    md.push("");
  }

  md.push("---");
  md.push("*Generated by IBM Bob Builders Challenge — AI Launch Vehicle Selector*");
  return md.join("\n");
}

function buildCsv(payload: ExportPayload): string {
  const rows: string[][] = [];
  rows.push([
    "Rank", "Vehicle", "Provider", "Type", "Score",
    "Cost Score", "Schedule Score", "Orbit Score",
    "Est. Cost USD", "Lead Time Min (mo)", "Lead Time Max (mo)",
    "Inclination Flexibility", "Orbit Types", "Status", "Notes"
  ]);
  payload.ranked.forEach((m) => {
    rows.push([
      String(m.rank),
      m.entry.vehicle,
      m.entry.provider,
      m.entry.type,
      String(m.score),
      String(m.score_breakdown.cost_score),
      String(m.score_breakdown.schedule_score),
      String(m.score_breakdown.orbit_score),
      m.estimated_cost_usd != null ? String(m.estimated_cost_usd) : "",
      String(m.entry.integration.lead_time_months.min),
      String(m.entry.integration.lead_time_months.max),
      m.entry.orbit_options.inclination_flexibility,
      m.entry.orbit_options.supported_orbit_types.join("; "),
      m.entry.status,
      m.entry.notes,
    ]);
  });
  payload.eliminated.forEach((m) => {
    rows.push([
      "ELIMINATED",
      m.entry.vehicle,
      m.entry.provider,
      m.entry.type,
      "", "", "", "", "",
      String(m.entry.integration.lead_time_months.min),
      String(m.entry.integration.lead_time_months.max),
      m.entry.orbit_options.inclination_flexibility,
      m.entry.orbit_options.supported_orbit_types.join("; "),
      m.entry.status,
      m.elimination_reason ?? m.entry.notes,
    ]);
  });

  return rows
    .map((r) => r.map((cell) => `"${cell.replace(/"/g, '""')}"`).join(","))
    .join("\n");
}

